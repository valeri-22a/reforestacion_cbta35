<p style="color: green;">Desabasto y contaminación del agua:</p>El plantel contaba previamente con un pozo propio para el suministro de agua; sin embargo, 
quedó fuera de servicio debido a problemas de contaminación que la inutilizaron para el consumo de los estudiantes 
y el agua que hay en la institución suele acabarse rápidamente que luego no hay para los baños. 
Esto ha derivado que hay días que la escuela se quede sin agua o que los baños huelan mal. <br>
        
<p style="color: green;">Degradación del suelo y factores ambientales:</p> La calidad del suelo es sumamente baja, presentando aridez y pérdida de materia orgánica. 
Esto, combinado con las variaciones climáticas extremas y los efluvios provenientes del antiguo basurero, limita el aprovechamiento de los espacios al aire libre. <br>
        
<p style="color: green;">Plaga de tuzas:</p> Se ha registrado una proliferación descontrolada de tuzas en las áreas verdes y terrenos del plantel. 
Esta plaga no solo deteriora la infraestructura del suelo mediante la excavación de túneles, sino que también afecta la vegetación existente 
y representa un riesgo para las actividades prácticas del alumnado.



